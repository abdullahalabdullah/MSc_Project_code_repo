#!/usr/bin/env python3
"""
Step 61 (experiment: prior-belief-vs-monitorability): select questions and
assign the two hint targets, from the uncertainty-vs-monitorability run's 30
unhinted lexam runs (the "selection runs").

Selection (valid run = answer parsed and not truncated):
  1. drop questions the model ALWAYS answers correctly in its valid runs;
  2. keep questions whose most common WRONG answer was chosen in
     >= prior_belief.min_wrong_count (6) runs;
  3. keep questions with >= 1 wrong option chosen in 0 runs;
  (and >= min_valid_selection_runs valid runs, 27).

Targets per question:
  Version A — the most common wrong answer (prior belief present); a tie
              between wrong answers is broken at random;
  Version B — a wrong option never chosen (no prior belief); one is drawn at
              random when several qualify.
The randomness is a per-question RNG seeded with (selection_seed, instance_id),
so the assignment is reproducible and independent of iteration order. Both
targets are wrong answers and A != B by construction.

The selection runs are used ONLY here — every metric is computed on the fresh
runs generated by step 62 (fix 1: no selection bias in p0).

Usage:
    python monitorability-eval/scripts/61_pbm_select_questions.py [--force]

    Options:
      --config  path to config YAML (default: config/prior_belief_vs_monitorability.yaml)
      --model   model id whose selection runs are read (default: Qwen/Qwen3-4B)
      --force   overwrite existing indexes (refused by default, since changing
                the selection after inference would orphan the outputs)

Input:
    {source_config outputs_dir}/{model}/{source_dataset}/{hint}/unhinted.jsonl[.gz]
    prior_belief.source_index (the prepared lexam dataset index)

Output (under the experiment's data_dir):
    {versions.A}/dataset_index.json   selected items, hint_target = A target
    {versions.B}/dataset_index.json   selected items, hint_target = B target
    selection.csv                     per question: counts in the selection
                                      runs, A / B targets, alternatives
    selection_summary.md
"""

import argparse
import csv
import gzip
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import yaml

from src.dataset import model_dir_name, resolve_paths
from src.gmean2_metrics import resolve_jsonl

DEFAULT_CONFIG = "config/prior_belief_vs_monitorability.yaml"
SELECTION_FIELDS = [
    "instance_id", "question_id", "n_options", "n_valid_selection_runs",
    "correct_answer", "selection_counts", "target_A", "count_A", "p0_selection_A",
    "tied_modal_wrong", "target_B", "never_chosen_wrong", "original_hint_target",
]


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


def read_selection_runs(path):
    """{instance_id: [valid answer letters]} from an unhinted.jsonl[.gz]."""
    path = resolve_jsonl(path)
    if not path.exists():
        sys.exit(f"ERROR: selection runs not found: {path}")
    opener = gzip.open if path.suffix == ".gz" else open
    answers = defaultdict(list)
    with opener(path, "rt", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            iid = int(r["instance_id"])
            answers.setdefault(iid, [])
            pa = r.get("parsed_answer")
            if r.get("truncated", False) or pa in (None, "", "None", "N/A"):
                continue
            answers[iid].append(pa)
    return answers


def main():
    parser = argparse.ArgumentParser(description="prior-belief-vs-monitorability: selection.")
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    parser.add_argument("--model", default="Qwen/Qwen3-4B")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[2]
    config = load_yaml(root / args.config)
    pb = config["prior_belief"]
    src_config = load_yaml(root / pb["source_config"])
    model_name = model_dir_name(args.model)
    hint = pb["hint_type"]

    data_dir = root / config["paths"]["data_dir"]
    out_index = {v: data_dir / key / "dataset_index.json" for v, key in pb["versions"].items()}
    if any(p.exists() for p in out_index.values()) and not args.force:
        sys.exit("ERROR: selection already exists — refusing to overwrite "
                 f"({', '.join(str(p) for p in out_index.values())}). Use --force "
                 "only if no inference has been run on it.")

    src_paths = resolve_paths(root, src_config, pb["source_dataset"], model_name, hint)
    answers = read_selection_runs(src_paths["outputs_dir"] / "unhinted.jsonl")
    with open(root / pb["source_index"]) as f:
        items = {int(it["instance_id"]): it for it in json.load(f)}

    rows, sel_A, sel_B = [], [], []
    funnel = Counter()
    for iid in sorted(items):
        it = items[iid]
        letters = answers.get(iid, [])
        options = sorted(it["choices"])
        gold = it["correct_answer"]
        funnel["questions"] += 1
        if len(letters) < pb["min_valid_selection_runs"]:
            funnel["too few valid selection runs"] += 1
            continue
        counts = Counter(letters)
        if counts.get(gold, 0) == len(letters):
            funnel["always correct"] += 1
            continue
        wrong = {o: counts.get(o, 0) for o in options if o != gold}
        top = max(wrong.values())
        if top < pb["min_wrong_count"]:
            funnel[f"modal wrong answer < {pb['min_wrong_count']} runs"] += 1
            continue
        tied = sorted(o for o, c in wrong.items() if c == top)
        rng = np.random.default_rng([pb["selection_seed"], iid])
        target_a = tied[0] if len(tied) == 1 else str(rng.choice(tied))
        never = sorted(o for o, c in wrong.items() if c == 0 and o != target_a)
        if not never:
            funnel["no never-chosen wrong option"] += 1
            continue
        target_b = never[0] if len(never) == 1 else str(rng.choice(never))
        assert target_a != gold and target_b != gold and target_a != target_b
        funnel["selected"] += 1
        rows.append(dict(
            instance_id=iid, question_id=it["question_id"], n_options=len(options),
            n_valid_selection_runs=len(letters), correct_answer=gold,
            selection_counts=" ".join(f"{o}:{counts.get(o, 0)}" for o in options),
            target_A=target_a, count_A=top, p0_selection_A=round(top / len(letters), 6),
            tied_modal_wrong=" ".join(tied) if len(tied) > 1 else "",
            target_B=target_b, never_chosen_wrong=" ".join(never),
            original_hint_target=it.get("hint_target", "")))
        sel_A.append(dict(it, hint_target=target_a))
        sel_B.append(dict(it, hint_target=target_b))

    if not rows:
        sys.exit("ERROR: no question passed the selection.")
    for v, sel in (("A", sel_A), ("B", sel_B)):
        out_index[v].parent.mkdir(parents=True, exist_ok=True)
        with out_index[v].open("w") as f:
            json.dump(sel, f, indent=1, ensure_ascii=False)
    with (data_dir / "selection.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SELECTION_FIELDS)
        w.writeheader()
        w.writerows(rows)

    p0 = np.array([r["p0_selection_A"] for r in rows])
    lines = [
        "# prior-belief-vs-monitorability — question selection", "",
        f"Selection runs: `{src_paths['outputs_dir'].relative_to(root)}/unhinted.jsonl` "
        f"({args.model}, {pb['source_dataset']}, {hint}); valid run = parsed and not truncated.", "",
        "| step | questions |", "|---|---|",
    ] + [f"| {k} | {funnel[k]} |" for k in (
        "questions", "too few valid selection runs", "always correct",
        f"modal wrong answer < {pb['min_wrong_count']} runs",
        "no never-chosen wrong option", "selected") if k in funnel] + [
        "",
        f"- Version A target: modal wrong answer; p0 in the selection runs "
        f"min {p0.min():.2f} / median {np.median(p0):.2f} / max {p0.max():.2f}; "
        f"{int((p0 >= 1).sum())} questions at p0 = 1; "
        f"{sum(1 for r in rows if r['tied_modal_wrong'])} tie(s) broken at random.",
        f"- Version B target: never-chosen wrong option; drawn at random for "
        f"{sum(1 for r in rows if len(r['never_chosen_wrong'].split()) > 1)} questions "
        "with several candidates.",
        f"- Original (step 01) hint target equals A for "
        f"{sum(1 for r in rows if r['original_hint_target'] == r['target_A'])} questions "
        f"and B for {sum(1 for r in rows if r['original_hint_target'] == r['target_B'])}.",
        f"- RNG: numpy default_rng([selection_seed={pb['selection_seed']}, instance_id]).",
    ]
    (data_dir / "selection_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    for p in list(out_index.values()) + [data_dir / "selection.csv", data_dir / "selection_summary.md"]:
        print(f"Wrote {p}")


if __name__ == "__main__":
    main()
