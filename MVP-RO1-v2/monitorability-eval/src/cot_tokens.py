"""
CoT token-length helpers for the max_new_tokens decision.

These are kept separate from gmean2_metrics so the token-length analysis can be
re-run on its own (scripts/08_cot_token_analysis.py) without touching the
g-mean^2 computation. `token_count` is the FULL completion length (thinking
trace + final answer) as generated by vLLM. Two views are produced:

  1. Per-condition stats (mean/std/min/max), RUN LEVEL: every valid run's
     token_count pooled per condition — the same methodology as
     compute_gmean2(...)["cot_tokens"]; this module only pools it across
     datasets for the "overall" row. Valid = not truncated + answer parsed,
     so the followed/not-followed rows partition the hinted row exactly.

  2. Token-length BUCKETS over the raw per-sample token_count of every response
     (both arms, INCLUDING truncated/unparsed), plus a truncation count. This is
     the view that actually informs max_new_tokens: it shows how many individual
     generations land in each length band and how many hit the cap
     (truncated=True).
"""

import numpy as np

# Bucket upper edges (in tokens). A response with token_count t falls in the
# first bucket whose edge it is strictly below; counts at/above the last edge go
# to the open-ended "N+" bucket. Powers-of-two ladder up to the largest
# configured max_new_tokens (32768).
DEFAULT_BUCKET_EDGES = [512, 1024, 2048, 4096, 8192, 16384, 32768]


def bucket_labels(edges: list = DEFAULT_BUCKET_EDGES) -> list:
    """Human-readable labels for the buckets defined by `edges`, in order."""
    labels = []
    lo = 0
    for hi in edges:
        labels.append(f"{lo}-{hi}")
        lo = hi
    labels.append(f"{edges[-1]}+")
    return labels


def bucket_counts(records: list, edges: list = DEFAULT_BUCKET_EDGES,
                  count_truncated_as_overflow: bool = True) -> dict:
    """Count responses into the token-length buckets defined by `edges`.

    `records` is a list of response dicts, each with a `token_count` and a
    `truncated` flag. A non-truncated response is placed by its token_count in
    the half-open interval [lo, hi).

    A TRUNCATED response is counted in the open-ended top bucket (the last
    `bucket_labels` entry) regardless of its token_count: its true length is
    censored — known only to EXCEED the model's max_new_tokens — so it belongs
    with the overflow tail, not at the cap value in a middle bucket (e.g. a
    16384-capped run must not record its truncated responses as "16384-32768"
    normal-length traces). Pass count_truncated_as_overflow=False to bucket
    purely by token_count.

    Returns an ordered {label: count} dict (one key per bucket_labels entry).
    """
    labels = bucket_labels(edges)
    counts = {label: 0 for label in labels}
    for r in records:
        if count_truncated_as_overflow and r.get("truncated", False):
            counts[labels[-1]] += 1
            continue
        t = r.get("token_count")
        if t is None:
            continue
        placed = False
        lo = 0
        for hi, label in zip(edges, labels):
            if lo <= t < hi:
                counts[label] += 1
                placed = True
                break
            lo = hi
        if not placed:  # t >= edges[-1]
            counts[labels[-1]] += 1
    return counts


def raw_token_stats(records: list) -> dict:
    """mean/std/min/max/n over the raw per-sample token_count of `records`.

    Only records carrying a non-null token_count are counted. Unlike the
    per-instance-mean condition table, this is the raw per-response distribution.
    """
    vals = [r["token_count"] for r in records if r.get("token_count") is not None]
    if not vals:
        return {"mean": None, "std": None, "min": None, "max": None, "n": 0}
    return {
        "mean": float(np.mean(vals)),
        # Sample std (ddof=1), consistent with gmean2_metrics / the SEM; n<2 -> 0.0.
        "std": float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0,
        "min": int(np.min(vals)),
        "max": int(np.max(vals)),
        "n": len(vals),
    }


def truncation_stats(records: list) -> dict:
    """Count and rate of truncated responses (token_count hit max_new_tokens)."""
    total = len(records)
    truncated = sum(1 for r in records if r.get("truncated", False))
    return {
        "total": total,
        "truncated": truncated,
        "rate": (truncated / total) if total else None,
    }
